DROP TABLE IF EXISTS ACSBV3_print_info;

CREATE TABLE ACSBV3_print_info
(

  `auto`   INT AUTO_INCREMENT PRIMARY KEY,
  `part`   INT,
  `output` VARCHAR(255)

);



