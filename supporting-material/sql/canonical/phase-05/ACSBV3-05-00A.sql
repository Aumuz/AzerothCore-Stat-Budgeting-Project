/*=============================================================================================================================================
  2. Create Print Header Procedure: ACSBV3_print_header
=============================================================================================================================================*/

DELIMITER $$

DROP PROCEDURE IF EXISTS ACSBV3_print_header $$

CREATE PROCEDURE ACSBV3_print_header ( IN `ARG_01` TEXT )

BEGIN

  SELECT `output` AS `` FROM ACSBV3_print_info WHERE `part` = 1

    UNION ALL

    SELECT CONCAT ( "##  ", RPAD ( `ARG_01`, 115, " " ), "  ##" ) AS ``

    UNION ALL

  SELECT `output` AS `` FROM ACSBV3_print_info WHERE `part` = 2

    UNION ALL

    SELECT CONCAT ( RPAD ( NOW(), 111, " " ), @SCRIPT, " (v", @VERSION, ")" ) AS ``

    UNION ALL

  SELECT `output` AS `` FROM ACSBV3_print_info WHERE `part` = 3;

END $$

DELIMITER ;



/*=============================================================================================================================================
  3. Create Print Footer Procedure: ACSBV3_print_footer
=============================================================================================================================================*/

DELIMITER $$

DROP PROCEDURE IF EXISTS ACSBV3_print_footer $$

CREATE PROCEDURE ACSBV3_print_footer ( )

BEGIN

  SELECT `output` AS `` FROM ACSBV3_print_info WHERE `part` = 3

    UNION ALL

    SELECT CONCAT ( RPAD ( NOW(), 111, " " ), @SCRIPT, " (v", @VERSION, ")" ) AS ``

    UNION ALL

  SELECT `output` AS `` FROM ACSBV3_print_info WHERE `part` = 4;

END $$

DELIMITER ;



